CREATE TABLE IF NOT EXISTS proposals (
    id BINARY(16) NOT NULL COMMENT '제안 식별자',
    contract_request_id BINARY(16) NOT NULL COMMENT '계약 요청 식별자',
    vendor_id BINARY(16) NOT NULL COMMENT '화주 식별자',
    agency_id BINARY(16) NOT NULL COMMENT '대리점 식별자',
    unit_price DECIMAL(15, 2) NOT NULL COMMENT '대표 박스당 제안 단가',
    initial_unit_price DECIMAL(15, 2) NOT NULL COMMENT '최초 대표 제안 단가',
    final_unit_price DECIMAL(15, 2) NULL COMMENT '최종 대표 협의 단가',
    pending_negotiation_id BINARY(16) NULL COMMENT '응답 대기 중인 협의 이벤트 식별자',
    next_sequence BIGINT NOT NULL DEFAULT 1 COMMENT '다음 협의 이벤트 순번',
    pickup_start_time VARCHAR(10) NOT NULL COMMENT '집하 가능 시작 시간',
    pickup_end_time VARCHAR(10) NOT NULL COMMENT '집하 가능 종료 시간',
    saturday_delivery_available BOOLEAN NOT NULL COMMENT '토요일 배송 가능 여부',
    return_available BOOLEAN NOT NULL COMMENT '반품 처리 가능 여부',
    cold_chain_type VARCHAR(30) NOT NULL COMMENT '지원 콜드체인 유형',
    memo VARCHAR(255) NULL COMMENT '제안 메모',
    status VARCHAR(30) NOT NULL COMMENT '제안 상태',
    created_at DATETIME(6) NOT NULL COMMENT '생성 시각',
    updated_at DATETIME(6) NOT NULL COMMENT '마지막 수정 시각',
    PRIMARY KEY (id),
    UNIQUE KEY uk_proposals_contract_request_agency (contract_request_id, agency_id),
    KEY idx_proposals_contract_request_id (contract_request_id),
    KEY idx_proposals_vendor_id (vendor_id),
    KEY idx_proposals_agency_id (agency_id),
    KEY idx_proposals_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='대리점 제안';

