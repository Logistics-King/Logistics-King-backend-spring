CREATE TABLE IF NOT EXISTS contract_requests (
    id BINARY(16) NOT NULL COMMENT '계약 요청 식별자',
    type VARCHAR(30) NOT NULL COMMENT '계약 요청 유형',
    requester_type VARCHAR(30) NOT NULL COMMENT '요청자 유형',
    requester_id BINARY(16) NOT NULL COMMENT '요청자 식별자',
    approver_type VARCHAR(30) NOT NULL COMMENT '승인자 유형',
    approver_id BINARY(16) NULL COMMENT '승인자 식별자',
    product_id BINARY(16) NULL COMMENT '대표 배송 품목 템플릿 식별자',
    pickup_region VARCHAR(100) NOT NULL COMMENT '집하 지역',
    pickup_address VARCHAR(255) NULL COMMENT '집하 주소',
    contract_type VARCHAR(30) NOT NULL DEFAULT 'SINGLE' COMMENT '계약 유형',
    pickup_date_from DATE NULL COMMENT '집하 희망 시작일',
    pickup_date_to DATE NULL COMMENT '집하 희망 종료일',
    delivery_date_from DATE NULL COMMENT '배송 희망 시작일',
    delivery_date_to DATE NULL COMMENT '배송 희망 종료일',
    recurring_pickup_cycle VARCHAR(30) NULL COMMENT '정기 집하 주기',
    recurring_pickup_days_of_week VARCHAR(100) NULL COMMENT '정기 집하 요일 목록',
    recurring_pickup_day_of_month INT NULL COMMENT '정기 집하 월 기준 일자',
    monthly_volume INT NOT NULL COMMENT '월 예상 물량',
    product_category VARCHAR(30) NOT NULL COMMENT '대표 품목 카테고리',
    product_name VARCHAR(100) NOT NULL COMMENT '대표 품목명',
    box_size VARCHAR(30) NOT NULL COMMENT '대표 박스 규격',
    pickup_start_time VARCHAR(10) NOT NULL COMMENT '집하 가능 시작 시간',
    pickup_end_time VARCHAR(10) NOT NULL COMMENT '집하 가능 종료 시간',
    saturday_delivery_required BOOLEAN NOT NULL COMMENT '토요일 배송 필요 여부',
    return_required BOOLEAN NOT NULL COMMENT '반품 처리 필요 여부',
    cold_chain_type VARCHAR(30) NOT NULL COMMENT '대표 콜드체인 유형',
    target_unit_price DECIMAL(15, 2) NULL COMMENT '희망 박스당 단가',
    memo VARCHAR(255) NULL COMMENT '계약 요청 메모',
    status VARCHAR(30) NOT NULL COMMENT '계약 요청 상태',
    created_at DATETIME(6) NOT NULL COMMENT '생성 시각',
    updated_at DATETIME(6) NOT NULL COMMENT '마지막 수정 시각',
    PRIMARY KEY (id),
    KEY idx_contract_requests_requester (requester_type, requester_id),
    KEY idx_contract_requests_approver (approver_type, approver_id),
    KEY idx_contract_requests_product_id (product_id),
    KEY idx_contract_requests_status (status),
    KEY idx_contract_requests_open_agency (type, status, approver_type, approver_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='계약 요청';

